#include <stdio.h>

int main()
{
    // \n = quebra de linha
    printf("Linha 1\nLinha 2\nLinha 3\n");

    // \t = tabulacao
    printf("\nNome:\tJoao\n");
    printf("Idade:\t20\n");

    // \" = aspas dentro do texto
    printf("\nMensagem: \"Ola!\"\n");

    // \\ = barra invertida
    printf("Caminho: C:\\temp\n");

    // %% = simbolo de porcento
    printf("Desconto: 10%%\n");

    return 0;
}